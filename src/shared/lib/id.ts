/**
 * Ключ идемпотентности для записи: контракт требует `requestId` в каждом
 * POST/PUT, чтобы повтор запроса не создал вторую запись.
 *
 * Считается из `Math.random`, и этого достаточно: ключ не секрет и не
 * проверяется на подлинность — от него нужна только неповторимость. Появится
 * место, где нужен криптографический идентификатор, — там появится
 * `expo-crypto.randomUUID`, а не этот файл.
 */
export function requestId(): string {
  const hex = (length: number) =>
    Array.from({ length }, () => Math.floor(Math.random() * 16).toString(16)).join('');

  // Форма v4: версия и вариант на своих местах — сервер проверяет формат.
  return `${hex(8)}-${hex(4)}-4${hex(3)}-${'89ab'[Math.floor(Math.random() * 4)]}${hex(3)}-${hex(12)}`;
}
