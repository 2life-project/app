import { onSignOut } from '@/core/auth';

import { clearBandReadings } from './band-readings';
import { clearBodyProfile } from './body-profile';

/**
 * Личные данные уходят вместе с человеком.
 *
 * Показания браслета и профиль тела принадлежат не телефону, а тому, кто их
 * намерил: телефоном пользуются двое, и второй не должен увидеть чужой пульс,
 * сон и вес — ни на экране, ни в расчётах, которые уедут на его устройство.
 *
 * Подписка — побочный эффект импорта этого файла, и подключает её публичный
 * вход домена. Ядро о доменных сущностях не знает и знать не должно, поэтому
 * они приходят к нему сами, а не наоборот.
 *
 * Привязка браслета здесь не трогается намеренно: устройство принадлежит
 * телефону, а не аккаунту, — так решено в docs/decisions.md.
 */
onSignOut(() => {
  clearBodyProfile();
  clearBandReadings();
});
