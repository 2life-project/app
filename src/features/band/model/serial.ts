/**
 * Последовательная запись на диск.
 *
 * Оба хранилища браслета — тренировки и архив суток — читают, дополняют и
 * пишут обратно. Два таких обмена внахлёст (двойное нажатие «Завершить»,
 * чтение сегодняшних суток одновременно с дочитыванием пропущенных) читают
 * одинаковое старое значение и затирают правки друг друга. Копии на устройстве
 * нет: тренировок оно не хранит вовсе, история живёт около четырёх суток.
 *
 * Очередь на модуль, а не блокировка на ключ: записей единицы, а разбираться
 * потом, почему пропала тренировка, нечем.
 */
let queue: Promise<unknown> = Promise.resolve();

export function serial<T>(run: () => Promise<T>): Promise<T> {
  const next = queue.then(run, run);
  // Хвост очереди не должен обрываться на отказе одной записи.
  queue = next.catch(() => undefined);
  return next;
}
