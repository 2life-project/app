import { Text } from '@/shared/ui';

/**
 * Пустая ячейка карточки. Одна на весь раздел: пока каждая карточка писала
 * своё, «нет данных» звучало десятью разными способами и ни одно из них не
 * отличало отсутствие замеров от незаконченного чтения.
 *
 * Разница важнее формулировки. Чтение всего раздела — это шесть обменов по
 * радио подряд, и всё это время пустая карточка честнее говорит «читаем», а не
 * «данных нет»: иначе человек уходит с экрана за секунду до того, как они
 * появятся.
 */
export function BandEmpty({ reading, text }: { reading: boolean; text: string }) {
  return (
    <Text variant="bodySmall" tone="muted">
      {reading ? 'Reading the band…' : text}
    </Text>
  );
}
