/**
 * Идентификатор события, которое устройство прислало само.
 *
 * Ставит его клиент, а не браслет: в кадре опознавателя нет, а сервер должен
 * уметь принять одно и то же дважды и не удвоить. Времени для этого мало —
 * замер и повторный запуск укладываются в одну секунду, и по метке времени они
 * неразличимы.
 *
 * Счётчик живёт в памяти процесса и после перезапуска начинается заново. Этого
 * достаточно: пара «адрес устройства + идентификатор» уникальна внутри сеанса,
 * а между сеансами разводит момент получения в миллисекундах.
 */
let counter = 0;

export function eventId(at: Date): string {
  counter += 1;
  return `${at.getTime().toString(36)}-${counter.toString(36)}`;
}
