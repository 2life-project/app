/** Имя, под которым браслет виден при поиске. */
export const BAND_NAME = 'ES100';

/**
 * Сервис, который браслет рекламирует до подключения. По нему радио отсеивает
 * чужие устройства ещё до того, как они дойдут до приложения.
 */
export const BAND_SERVICE = '00005555-0000-1000-8000-00805f9b34fb';

/** Служба протокола производителя: команды и отчёты. */
export const BAND_GATT_SERVICE = '000056ff-0000-1000-8000-00805f9b34fb';

/** Служба со списками возможностей — вторая половина того же протокола. */
export const BAND_CAPABILITY_SERVICE = '000055ff-0000-1000-8000-00805f9b34fb';

/**
 * По каким службам узнать браслет среди уже подключённых к системе.
 *
 * Рекламируемая служба тут не помогает: система хранит то, что у устройства
 * действительно есть, а не то, чем оно звало к себе. Поэтому спрашиваем все
 * три — что бы ни попало в системный кэш, браслет найдётся.
 */
export const BAND_SERVICES = [BAND_SERVICE, BAND_GATT_SERVICE, BAND_CAPABILITY_SERVICE];

/**
 * Сколько сканировать. Браслет рекламирует себя с паузами, и на пяти секундах
 * его регулярно не видно — это не отсутствие устройства, а слишком короткий поиск.
 */
export const SCAN_TIMEOUT_MS = 30_000;
